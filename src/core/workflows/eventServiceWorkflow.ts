/**
 * The lifecycle of one Service booked on one Event — independent of both
 * the catalog Service's own status and the Event's own status/lifecycle
 * stage. "cancelled" is a real terminal member (matching every other
 * module's status enum) rather than a deletion — cancelling an EventService
 * never removes it or the rows it already generated.
 */
const EVENT_SERVICE_TRANSITIONS: Record<EventServiceStatus, EventServiceStatus[]> = {
  proposed: ["confirmed", "cancelled"],
  confirmed: ["in_progress", "cancelled"],
  in_progress: ["completed", "cancelled"],
  completed: [],
  cancelled: [],
};

export function canTransitionEventServiceStatus(from: EventServiceStatus, to: EventServiceStatus): boolean {
  if (from === to) return false;
  return EVENT_SERVICE_TRANSITIONS[from].includes(to);
}

/**
 * The live `name`/`price_minor` overrides may be edited any time before the
 * booking reaches a terminal status — once `completed` or `cancelled`, the
 * record represents a finished/dead booking whose price and name should
 * stop moving, the same "terminal states lock down" rule
 * `EVENT_SERVICE_TRANSITIONS` already enforces for status itself.
 */
export function canOverrideEventService(status: EventServiceStatus): boolean {
  return status !== "completed" && status !== "cancelled";
}

/**
 * The definition of "usage" the Services Catalog/Health/Search surfaces all
 * share: how many EventServices currently represent real, non-cancelled
 * demand for a catalog Service. A `cancelled` EventService is excluded —
 * it's a booking that fell through, not evidence the Service is in use.
 * `completed` counts (a finished booking is still real historical usage).
 * `EVENT_SERVICE_TRANSITIONS` guarantees `cancelled` is reachable only from
 * a non-terminal status and never left once reached, so this predicate
 * alone is enough to know whether transitioning an EventService's status
 * could ever change a Service's usage count (see
 * useTransitionEventServiceStatus's own invalidation logic).
 */
export function countsTowardServiceUsage(status: EventServiceStatus): boolean {
  return status !== "cancelled";
}

/** A "pending" ChecklistItem or "planned" EventScheduleItem generated by an EventService is safe to delete outright if the EventService is removed — anything further along represents real work already done, and is preserved rather than silently destroyed. Matches the architecture review's explicit "never silently destroy work" recommendation. */
export function isGeneratedChecklistItemRemovable(status: string): boolean {
  return status === "pending";
}

export function isGeneratedScheduleItemRemovable(status: string): boolean {
  return status === "planned";
}

/** offset_minutes may be negative (before the event's own start) or positive (after) — resolveOffsetTime tolerates both. Returns null whenever eventStartTime isn't a well-formed "HH:MM" string, rather than throwing — a Service can still be assigned to an Event with no time set yet. */
function parseTimeToMinutes(time: string | null): number | null {
  if (!time) return null;
  const match = /^(\d{1,2}):(\d{2})$/.exec(time.trim());
  if (!match) return null;
  const hours = Number(match[1]);
  const minutes = Number(match[2]);
  if (hours > 23 || minutes > 59) return null;
  return hours * 60 + minutes;
}

function formatMinutesToTime(totalMinutes: number): string {
  const normalized = ((totalMinutes % 1440) + 1440) % 1440;
  const hours = Math.floor(normalized / 60);
  const minutes = normalized % 60;
  return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}`;
}

export function resolveOffsetTime(eventStartTime: string | null, offsetMinutes: number): string | null {
  const baseMinutes = parseTimeToMinutes(eventStartTime);
  if (baseMinutes === null) return null;
  return formatMinutesToTime(baseMinutes + offsetMinutes);
}

/** due_offset_days counts days BEFORE the Event date a checklist item is due (a positive value is earlier, matching how staff naturally describe deadlines — "3 days before the event"). Returns null whenever eventDate is unset, or offsetDays is null (no deadline at all). */
export function resolveOffsetDueDate(eventDate: string | null, offsetDays: number | null): string | null {
  if (!eventDate || offsetDays === null) return null;
  const parsed = new Date(`${eventDate}T00:00:00`);
  if (Number.isNaN(parsed.getTime())) return null;
  parsed.setDate(parsed.getDate() - offsetDays);
  return parsed.toISOString().slice(0, 10);
}


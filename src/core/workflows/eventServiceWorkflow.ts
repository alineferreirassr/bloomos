/**
 * The base price plus whichever add-ons were actually selected — extracted
 * as its own pure function (rather than inlined in the assignment plan) so
 * a future consumer that needs a price preview WITHOUT a full Event context
 * — Proposal Builder, most notably, per the pre-migration domain review's
 * §10 finding — can call this directly instead of faking one.
 */
export function computeServicePrice(basePriceMinor: number, addOns: ServiceAddOn[], selectedAddOnIds: string[]): number {
  const selectedAddOns = addOns.filter((addOn) => selectedAddOnIds.includes(addOn.id));
  return sumMinor([basePriceMinor, ...selectedAddOns.map((addOn) => addOn.price_delta_minor)]);
}

export interface ServiceRequirementsInput {
  inventoryTemplateItems: ServiceInventoryTemplateItem[];
  purchaseTemplateItems: ServicePurchaseTemplateItem[];
  budgetTemplateLines: ServiceBudgetTemplateLine[];
  teamRoleRequirements: ServiceTeamRoleRequirement[];
  vendorSuggestions: ServiceVendorSuggestion[];
}

export interface ServiceRequirementsPlan {
  inventoryRequirements: GeneratedInventoryRequirementSpec[];
  purchaseRequirements: GeneratedPurchaseRequirementSpec[];
  budgetLines: GeneratedBudgetLineSpec[];
  teamRequirements: GeneratedTeamRequirementSpec[];
  vendorAssignments: GeneratedVendorAssignmentSpec[];
}

/**
 * Maps every requirement/estimate template category straight across into
 * its generated Instance-layer shape — unlike checklist/timeline items,
 * none of these need offset resolution against the Event's date/time, so
 * this is a genuine 1:1 copy, extracted as its own pure function for the
 * same reason computeServicePrice was: an isolated, independently testable
 * and independently reusable step, not something only reachable by running
 * the full assignment plan.
 */
export function computeServiceRequirements(input: ServiceRequirementsInput): ServiceRequirementsPlan {
  const inventoryRequirements: GeneratedInventoryRequirementSpec[] = input.inventoryTemplateItems.map((item) => ({
    inventory_item_id: item.inventory_item_id,
    item_name: item.item_name,
    quantity: item.quantity,
  }));

  const purchaseRequirements: GeneratedPurchaseRequirementSpec[] = input.purchaseTemplateItems.map((item) => ({
    item_name: item.item_name,
    estimated_unit_cost_minor: item.estimated_unit_cost_minor,
    estimated_quantity: item.estimated_quantity,
    typical_vendor_id: item.typical_vendor_id,
  }));

  const budgetLines: GeneratedBudgetLineSpec[] = input.budgetTemplateLines.map((line) => ({
    label: line.label,
    category: line.category,
    estimated_revenue_minor: line.estimated_revenue_minor,
    estimated_cost_minor: line.estimated_cost_minor,
  }));

  const teamRequirements: GeneratedTeamRequirementSpec[] = input.teamRoleRequirements.map((role) => ({
    role_label: role.role_label,
    quantity: role.quantity,
    note: role.note,
  }));

  const vendorAssignments: GeneratedVendorAssignmentSpec[] = input.vendorSuggestions.map((suggestion) => ({
    vendor_id: suggestion.vendor_id,
    note: suggestion.note,
  }));

  return { inventoryRequirements, purchaseRequirements, budgetLines, teamRequirements, vendorAssignments };
}

/**
 * The single source of truth for what assigning a Service to an Event
 * generates — orchestration only. Every real computation lives in a named
 * pure function it calls (computeServicePrice, computeServiceRequirements,
 * plus the checklist/timeline mapping below, each already delegating its
 * own date/time math to resolveOffsetDueDate/resolveOffsetTime); this
 * function's only job is gathering their results into one plan. Both
 * ServicesRepository.mockRepository AND the future Supabase
 * `assign_service_to_event` RPC must produce exactly this same set of rows;
 * neither repository re-derives this logic independently (the same
 * "TypeScript workflow is the source of truth, SQL is its equivalent" rule
 * `derivePurchaseReceiptStatus`/`getInventoryMovementDelta` already
 * establish elsewhere in this codebase).
 *
 * Deliberately generates nothing for Finance or Inventory to act on
 * directly — every requirement row produced here is a draft/estimate a
 * human reviews before it becomes a real Purchase, Invoice, or Inventory
 * movement, per the architecture's "never auto-mutate a real ledger" rule.
 */
export function buildEventServiceAssignmentPlan(input: EventServiceAssignmentInput, context: EventServiceAssignmentContext): EventServiceAssignmentPlan {
  const selectedAddOnIds = context.selectedAddOnIds ?? [];
  const priceMinor = computeServicePrice(input.version.base_price_minor, input.addOns, selectedAddOnIds);
  const nameSnapshot = input.version.name_snapshot ?? input.service.name;

  // Sorted by display_order before mapping — mirrors the SQL RPC's `order by
  // display_order` exactly. Found and fixed during the pre-push migration
  // review: this function previously relied on whatever order its caller's
  // array happened to be in (harmless for the seeded mock data, since it
  // was already display_order-ordered, but a real parity gap against the
  // RPC for any Service whose template items were authored out of order).
  const checklistItems: GeneratedChecklistItemSpec[] = [...input.checklistTemplateItems]
    .sort((a, b) => a.display_order - b.display_order)
    .map((item) => {
      const dueDate = resolveOffsetDueDate(context.eventDate, item.due_offset_days);
      return {
        title: item.title,
        category: item.category,
        priority: item.priority,
        due_date: dueDate,
        template_snapshot: { title: item.title, category: item.category, priority: item.priority, due_date: dueDate },
      };
    });

  const scheduleItems: GeneratedScheduleItemSpec[] = [...input.timelineTemplateItems]
    .sort((a, b) => a.display_order - b.display_order)
    .map((item) => {
      const startTime = resolveOffsetTime(context.eventStartTime, item.offset_minutes_from_event_start);
      const endTime = startTime !== null && item.duration_minutes != null ? resolveOffsetTime(startTime, item.duration_minutes) : null;
      return {
        title: item.title,
        category: item.category,
        start_time: startTime,
        end_time: endTime,
        template_snapshot: { title: item.title, category: item.category, start_time: startTime, end_time: endTime },
      };
    });

  const requirements = computeServiceRequirements({
    inventoryTemplateItems: input.inventoryTemplateItems,
    purchaseTemplateItems: input.purchaseTemplateItems,
    budgetTemplateLines: input.budgetTemplateLines,
    teamRoleRequirements: input.teamRoleRequirements,
    vendorSuggestions: input.vendorSuggestions,
  });

  return {
    name: nameSnapshot,
    name_template_value: nameSnapshot,
    price_minor: priceMinor,
    price_template_value: priceMinor,
    currency: input.version.currency,
    selected_add_on_ids: selectedAddOnIds,
    checklistItems,
    scheduleItems,
    ...requirements,
  };
}
